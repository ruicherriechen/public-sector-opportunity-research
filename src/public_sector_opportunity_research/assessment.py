@dataclass(frozen=True)
class AssessmentRun:
    """Bundle an assessment with the exact retrieval evidence and trace ID."""

    assessment: OpportunityAssessment
    retrieval_trace_id: str
    retrieved_evidence: list[RetrievedEvidence]
    openai_response_id: str | None


class AssessmentError(RuntimeError):
    """Base class for safe, user-facing opportunity-assessment failures."""


class MissingOpenAIAPIKey(AssessmentError):
    """Report that ``OPENAI_API_KEY`` is absent without exposing secret data."""


class OpenAIAssessmentError(AssessmentError):
    """Report an API, refusal, incomplete response, or parse failure."""


class GroundingError(AssessmentError):
    """Report a model citation that was not present in retrieved evidence."""


class AssessmentGenerator(Protocol):
    """Describe the small generation interface used by the assessment service."""

    model_name: str

    def generate(
        self,
        question: str,
        agency_name: str,
        evidence: Sequence[SemanticSearchResult],
        awards: Sequence[DocumentedAward],
    ) -> tuple[OpportunityAssessmentDraft, str | None]:
        """Return a validated draft and optional provider response identifier."""


class OpenAIAssessmentGenerator:
    """Call the official OpenAI SDK's Responses API with Structured Outputs."""

    def __init__(self, model_name: str) -> None:
        """Remember a configurable Structured-Outputs-capable model name."""
        self.model_name = model_name

    def generate(
        self,
        question: str,
        agency_name: str,
        evidence: Sequence[SemanticSearchResult],
        awards: Sequence[DocumentedAward],
    ) -> tuple[OpportunityAssessmentDraft, str | None]:
        """Generate one strict assessment draft from bounded local evidence.

        Args:
            question: The unchanged research question being assessed.
            agency_name: Human-readable agency name from SQLite.
            evidence: At most ten reranked chunks from ``SemanticRetriever``.
            awards: Exact award metadata found by a deterministic SQL query.

        Returns:
            A Pydantic-validated draft and the Responses API response ID.

        Side effects and errors:
            Reads ``OPENAI_API_KEY`` from the process environment and makes one
            HTTPS API request. The key is never included in prompts or logs.
            Missing keys raise ``MissingOpenAIAPIKey``. SDK errors, refusals,
            incomplete output, and absent parsed output raise
            ``OpenAIAssessmentError`` without fabricating an assessment.
        """
        api_key = require_openai_api_key()

        # Import lazily so non-generative ingestion/retrieval commands remain
        # usable even when a beginner has not installed the OpenAI dependency.
        try:
            from openai import OpenAI
        except ImportError as exc:  # pragma: no cover - dependency install issue
            raise OpenAIAssessmentError(
                "The openai package is not installed; run pip install -r requirements.txt."
            ) from exc

        system_prompt = (
            "You assess public-sector software opportunities from supplied evidence only. "
            "Separate documented facts from model inferences. Cite only the exact source "
            "document IDs and chunk IDs supplied below. Never treat missing evidence as "
            "proof that no contract exists. A documented need without a documented award "
            "is potential, not proof of an open procurement. Use substantial overlap only "
            "when an award covers substantially the same scope; use partial for limited "
            "overlap. A notice of intent to award is not a confirmed executed contract. "
            "Keep the proposed status, procurement status, explanation, and commercial "
            "implications logically consistent. Do not invent dates, contract identifiers, "
            "vendors, or facts."
        )
        payload = {
            "research_question": question,
            "agency": agency_name,
            "retrieved_evidence": [asdict(item) for item in evidence],
            "deterministic_award_metadata": [
                award.model_dump(mode="json") for award in awards
            ],
        }

        try:
            # ``responses.parse`` converts the Pydantic model to strict JSON
            # Schema and validates the returned Structured Output automatically.
            response = OpenAI(api_key=api_key).responses.parse(
                model=self.model_name,
                input=[
                    {"role": "system", "content": system_prompt},
                    {
                        "role": "user",
                        "content": json.dumps(payload, sort_keys=True),
                    },
                ],
                text_format=OpportunityAssessmentDraft,
                store=False,
            )
        except Exception as exc:  # SDK exposes several provider-specific subclasses
            raise OpenAIAssessmentError(
                f"OpenAI assessment request failed ({type(exc).__name__})."
            ) from exc

        draft = getattr(response, "output_parsed", None)
        if draft is None:
            raise OpenAIAssessmentError(
                "OpenAI returned no parsed assessment (possibly refused or incomplete)."
            )
        return draft, getattr(response, "id", None)


def require_openai_api_key() -> str:
    """Return the environment API key or fail without logging its value."""
    api_key = os.getenv("OPENAI_API_KEY")
    if not api_key:
        raise MissingOpenAIAPIKey(
            "OPENAI_API_KEY is not set; no API assessment was generated."
        )
    return api_key


class OpportunityAssessmentService:
    """Combine retrieval, deterministic award checks, generation, and validation."""

    def __init__(
        self,
        store: SQLiteStore,
        retriever: SemanticRetriever,
        generator: AssessmentGenerator,
    ) -> None:
        """Attach services for one database evidence state."""
        self.store = store
        self.retriever = retriever
        self.generator = generator

    def assess(
        self,
        question: str,
        agency_id: str,
        top_k: int = 20,
        final_k: int = 10,
    ) -> AssessmentRun:
        """Retrieve evidence and return one grounded opportunity assessment.

        Semantic retrieval supplies at most ``final_k`` text chunks. A separate
        exact SQL query supplies award identity/dates so a low vector rank cannot
        be mistaken for proof that no award exists. With no retrieved evidence,
        the method returns a deterministic ``insufficient_evidence`` result and
        deliberately makes no API call.
        """
        retrieval = self.retriever.retrieve(
            question,
            agency_id=agency_id,
            top_k=top_k,
            final_k=final_k,
        )
        document_rows = self.store.list_documents_for_agency(agency_id)
        agency_name = (
            str(document_rows[0]["agency_name"]) if document_rows else agency_id
        )
        awards = [_award_from_row(row) for row in self.store.list_documented_awards(agency_id)]

        # An empty result cannot support citations. Returning a deterministic
        # schema-valid result is safer than asking a model to fill required fields.
        if not retrieval.results:
            assessment = OpportunityAssessment(
                agency=agency_name,
                opportunity_title="Insufficient evidence to identify an opportunity",
                agency_need_and_supporting_evidence=[],
                opportunity_status="insufficient_evidence",
                documented_procurement_status="none",
                award_scope_overlap="unknown",
                commercial_implications=[],
                explanation_of_assessment=[],
                supporting_source_ids=[],
                supporting_chunk_ids=[],
                relevant_publication_and_contract_dates=[],
                uncertainties_and_information_gaps=[
                    "No eligible evidence chunks were retrieved, so no opportunity claim can be supported."
                ],
                # Award metadata is not exposed as a citation unless its source
                # document was also part of retrieved evidence (none is here).
                documented_awards=[],
            )
            return _assessment_run(assessment, retrieval, None)

        draft, response_id = self.generator.generate(
            question, agency_name, retrieval.results, awards
        )
        assessment = finalize_assessment(draft, retrieval.results, awards)
        return _assessment_run(assessment, retrieval, response_id)


def finalize_assessment(
    draft: OpportunityAssessmentDraft,
    evidence: Sequence[SemanticSearchResult],
    awards: Sequence[DocumentedAward],
) -> OpportunityAssessment:
    """Validate citations and deterministically calculate dates and status.

    The language model supplies qualitative scope overlap, prose, and explicit
    fact/inference labels. Python owns the rules that depend on database state:
    whether an award row exists, whether its chunk was retrieved, and whether
    its source date follows the documented need. Invalid citations raise rather
    than being silently deleted.
    """
    _validate_citations(draft, evidence)

    evidence_by_document = {item.document_id: item for item in evidence}
    canonical_source_ids, canonical_chunk_ids = _citation_sets(draft)
    need_sources = {
        source_id
        for statement in draft.agency_need_and_supporting_evidence
        if statement.statement_type == "documented_fact"
        for source_id in statement.source_document_ids
        if source_id in evidence_by_document
        and evidence_by_document[source_id].document_type in {"strategy", "budget"}
    }
    documented_need = bool(need_sources)
    retrieved_award_ids = {
        item.document_id
        for item in evidence
        if item.document_type in {"intent-to-award", "confirmed-award", "award"}
    }
    award_ids = {award.document_id for award in awards}
    cited_award_ids = award_ids & retrieved_award_ids & canonical_source_ids
    procurement_status = _documented_procurement_status(awards)

    # Dates are read from SQLite-backed result metadata. Model-proposed dates
    # are intentionally replaced so chronology never depends on an LLM guess.
    dates = _deterministic_dates(canonical_source_ids, evidence, awards)
    status, rule_uncertainties = _determine_status(
        documented_need=documented_need,
        need_sources=need_sources,
        evidence_by_document=evidence_by_document,
        awards=awards,
        cited_award_ids=cited_award_ids,
        procurement_status=procurement_status,
        overlap=draft.award_scope_overlap,
    )

    # Preserve valid model content, then replace fields governed by deterministic
    # application rules and validate the complete final Pydantic schema again.
    values = draft.model_dump()
    cited_awards = [
        award for award in awards if award.document_id in cited_award_ids
    ]
    explanations, implications = _consistent_narratives(
        status=status,
        procurement_status=procurement_status,
        overlap=draft.award_scope_overlap,
        need_sources=need_sources,
        cited_award_ids=cited_award_ids,
        evidence=evidence,
    )
    values.update(
        agency=evidence[0].agency_name,
        opportunity_status=status,
        documented_procurement_status=procurement_status,
        supporting_source_ids=sorted(canonical_source_ids),
        supporting_chunk_ids=sorted(canonical_chunk_ids),
        explanation_of_assessment=explanations,
        commercial_implications=implications,
        relevant_publication_and_contract_dates=dates,
        uncertainties_and_information_gaps=list(
            dict.fromkeys(
                draft.uncertainties_and_information_gaps + rule_uncertainties
            )
        ),
        documented_awards=cited_awards,
    )
    return OpportunityAssessment.model_validate(values)


def _validate_citations(
    draft: OpportunityAssessmentDraft,
    evidence: Sequence[SemanticSearchResult],
) -> None:
    """Reject source/chunk citations not present in the retrieved evidence."""
    allowed_documents = {item.document_id for item in evidence}
    allowed_chunks = {item.chunk_id for item in evidence}
    chunk_to_document = {item.chunk_id: item.document_id for item in evidence}

    cited_documents, cited_chunks = _citation_sets(draft)
    statements = (
        draft.agency_need_and_supporting_evidence
        + draft.commercial_implications
        + draft.explanation_of_assessment
    )
    for statement in statements:
        for chunk_id in statement.chunk_ids:
            if chunk_id in chunk_to_document and chunk_to_document[chunk_id] not in set(
                statement.source_document_ids
            ):
                raise GroundingError(
                    f"Chunk citation {chunk_id} does not belong to the statement's source IDs."
                )
    cited_documents.update(
        item.source_document_id for item in draft.relevant_publication_and_contract_dates
    )

    unknown_documents = cited_documents - allowed_documents
    unknown_chunks = cited_chunks - allowed_chunks
    if unknown_documents or unknown_chunks:
        raise GroundingError(
            "Assessment cited evidence that retrieval did not supply: "
            f"documents={sorted(unknown_documents)}, chunks={sorted(unknown_chunks)}"
        )


def _citation_sets(
    draft: OpportunityAssessmentDraft,
) -> tuple[set[str], set[str]]:
    """Collect top-level and statement citations into canonical unique sets."""
    documents = set(draft.supporting_source_ids)
    chunks = set(draft.supporting_chunk_ids)
    statements = (
        draft.agency_need_and_supporting_evidence
        + draft.commercial_implications
        + draft.explanation_of_assessment
    )
    for statement in statements:
        documents.update(statement.source_document_ids)
        chunks.update(statement.chunk_ids)
    return documents, chunks


def _determine_status(
    *,
    documented_need: bool,
    need_sources: set[str],
    evidence_by_document: dict[str, SemanticSearchResult],
    awards: Sequence[DocumentedAward],
    cited_award_ids: set[str],
    procurement_status: DocumentedProcurementStatus,
    overlap: AwardScopeOverlap,
) -> tuple[OpportunityStatus, list[str]]:
    """Apply award-presence, citation, overlap, and chronology business rules."""
    uncertainties: list[str] = []
    if not documented_need:
        return "insufficient_evidence", [
            "Retrieved evidence did not document a strategy or budget need with valid citations."
        ]

    if procurement_status == "none":
        return "potential", [
            "No procurement award record is documented in this scenario database; this is not proof that no contract exists."
        ]

    if procurement_status == "intent_to_award":
        return "potential", [
            "An intent-to-award notice is documented, but it is not proof of a signed or executed contract."
        ]

    if procurement_status == "conflicting_evidence":
        return "insufficient_evidence", [
            "Confirmed-award metadata has missing or conflicting execution/publication dates."
        ]

    confirmed_ids = {
        award.document_id
        for award in awards
        if award.procurement_status == "confirmed_award"
    }
    cited_confirmed_ids = cited_award_ids & confirmed_ids
    if not cited_confirmed_ids:
        return "insufficient_evidence", [
            "The database contains a confirmed-award record, but no retrieved and cited confirmed-award chunk supports a scope comparison."
        ]

    # Compare structured source dates. An earlier award cannot deterministically
    # be treated as resolving a later need merely because its text is similar.
    latest_need_date = max(
        (
            _result_source_date(evidence_by_document[source_id])
            for source_id in need_sources
            if _result_source_date(evidence_by_document[source_id]) is not None
        ),
        default=None,
    )
    relevant_awards = [
        award for award in awards if award.document_id in cited_confirmed_ids
    ]
    award_dates = [
        value
        for award in relevant_awards
        if (value := award.execution_date) is not None
    ]
    latest_award_date = max(award_dates, default=None)
    if latest_need_date is None or latest_award_date is None:
        return "insufficient_evidence", [
            "Need-versus-award chronology could not be verified from structured source dates."
        ]
    if latest_award_date < latest_need_date:
        return "potential", [
            "The cited award predates the latest documented need and cannot establish that the later need was addressed."
        ]

    if overlap == "substantial":
        return "already_awarded", uncertainties
    if overlap == "partial":
        return "partially_addressed", uncertainties
    if overlap == "none":
        return "potential", [
            "A later award exists, but the model found no supported scope overlap; commercial availability still requires research."
        ]
    return "insufficient_evidence", [
        "A later award exists, but available evidence does not support a reliable scope-overlap judgment."
    ]


def _documented_procurement_status(
    awards: Sequence[DocumentedAward],
) -> DocumentedProcurementStatus:
    """Summarize exact procurement records without equating intent and execution."""
    if not awards:
        return "none"
    confirmed = [
        award for award in awards if award.procurement_status == "confirmed_award"
    ]
    if not confirmed:
        return "intent_to_award"

    # Confirmed status requires internally coherent structured dates. Text that
    # sounds final cannot compensate for missing or contradictory metadata.
    for award in confirmed:
        if (
            award.publication_date is None
            or award.effective_date is None
            or award.execution_date is None
            or not award.contract_id
            or not award.selected_vendor
            or award.execution_date != award.effective_date
            or award.execution_date > award.publication_date
            or (
                award.last_updated_date is not None
                and award.last_updated_date < award.publication_date
            )
        ):
            return "conflicting_evidence"
    return "confirmed_award"


def _consistent_narratives(
    *,
    status: OpportunityStatus,
    procurement_status: DocumentedProcurementStatus,
    overlap: AwardScopeOverlap,
    need_sources: set[str],
    cited_award_ids: set[str],
    evidence: Sequence[SemanticSearchResult],
) -> tuple[list[GroundedStatement], list[GroundedStatement]]:
    """Build explanation and commercial text from the final deterministic state.

    The API draft's narrative is intentionally replaced. Otherwise Python could
    correct a status while leaving prose that asserts the model's earlier,
    incompatible status—the exact inconsistency this validation prevents.
    """
    cited_sources = need_sources | cited_award_ids
    cited_chunks = [
        item.chunk_id for item in evidence if item.document_id in cited_sources
    ]
    source_ids = sorted(cited_sources)

    if procurement_status == "none":
        fact = "The cited strategy or budget evidence documents a modernization need; this scenario contains no confirmed-award record."
    elif procurement_status == "intent_to_award":
        fact = "The evidence includes an intent-to-award notice, which does not establish that a contract was signed or executed."
    elif procurement_status == "confirmed_award":
        fact = "The evidence and structured metadata document a later confirmed executed contract."
    else:
        fact = "A record claims a confirmed award, but its structured contract dates are missing or conflicting."

    status_text = {
        "potential": (
            "The opportunity is assessed as potential only; this does not prove that a procurement is currently open."
        ),
        "already_awarded": (
            "The later executed contract covers substantially the same scope, so the opportunity is assessed as already awarded."
        ),
        "partially_addressed": (
            "The executed contract overlaps only part of the need, so the opportunity is assessed as partially addressed."
        ),
        "insufficient_evidence": (
            f"The documented procurement status and {overlap} scope-overlap assessment do not support a conclusive commercial status."
        ),
    }[status]
    commercial_text = {
        "potential": (
            "Treat this as a research lead, not a confirmed open sale; verify current procurement and contract status before outreach."
        ),
        "already_awarded": (
            "A net-new sale for the awarded scope is unlikely; investigate only verified follow-on, option, recompete, or uncovered needs."
        ),
        "partially_addressed": (
            "Only needs outside the executed scope may remain; verify those gaps without assuming they are commercially available."
        ),
        "insufficient_evidence": (
            "Do not make a commercial recommendation until procurement status, dates, and scope can be reconciled."
        ),
    }[status]

    explanation = [
        GroundedStatement(
            text=fact,
            statement_type="documented_fact",
            source_document_ids=source_ids,
            chunk_ids=cited_chunks,
        ),
        GroundedStatement(
            text=status_text,
            statement_type="model_inference",
            source_document_ids=source_ids,
            chunk_ids=cited_chunks,
        ),
    ]
    implications = [
        GroundedStatement(
            text=commercial_text,
            statement_type="model_inference",
            source_document_ids=source_ids,
            chunk_ids=cited_chunks,
        )
    ]
    return explanation, implications


def _deterministic_dates(
    supporting_source_ids: Sequence[str] | set[str],
    evidence: Sequence[SemanticSearchResult],
    awards: Sequence[DocumentedAward],
) -> list[RelevantDate]:
    """Build relevant publication and contract dates from stored metadata."""
    supported = set(supporting_source_ids)
    dates: list[RelevantDate] = []
    seen: set[tuple[str, str, date]] = set()

    for item in evidence:
        if item.document_id not in supported or not item.publication_date:
            continue
        value = date.fromisoformat(item.publication_date)
        key = (item.document_id, "publication", value)
        if key not in seen:
            dates.append(
                RelevantDate(
                    label=f"Publication date: {item.document_title}",
                    date=value,
                    date_type="publication",
                    source_document_id=item.document_id,
                )
            )
            seen.add(key)

    for award in awards:
        if award.document_id not in supported:
            continue
        for label, kind, value in (
            ("Award publication date", "publication", award.publication_date),
            ("Contract execution date", "contract", award.execution_date),
            ("Award last-updated date", "last_updated", award.last_updated_date),
        ):
            if value is None:
                continue
            key = (award.document_id, kind, value)
            if key not in seen:
                dates.append(
                    RelevantDate(
                        label=label,
                        date=value,
                        date_type=kind,
                        source_document_id=award.document_id,
                    )
                )
                seen.add(key)
    return sorted(dates, key=lambda item: (item.date, item.source_document_id, item.label))


def _award_from_row(row: object) -> DocumentedAward:
    """Convert a named SQLite row into the public deterministic award model."""
    metadata = json.loads(row["metadata_json"])
    document_type = str(row["document_type"])
    # Document type is the database's status category. Metadata supplies exact
    # details, while missing details later make the record conflicting rather
    # than silently downgrading a claimed confirmed award to an intent notice.
    procurement_status: ProcurementRecordStatus = (
        "confirmed_award"
        if document_type == "confirmed-award"
        else "intent_to_award"
    )
    return DocumentedAward(
        document_id=row["document_id"],
        title=row["title"],
        procurement_status=procurement_status,
        contract_id=metadata.get("contract_id") or metadata.get("solicitation_id"),
        selected_vendor=metadata.get("selected_vendor"),
        source_url=row["source_url"],
        publication_date=_optional_date(row["publication_date"]),
        effective_date=_optional_date(row["effective_date"]),
        execution_date=_optional_date(metadata.get("execution_date")),
        last_updated_date=_optional_date(row["last_updated_date"]),
    )


def _optional_date(value: str | None) -> date | None:
    """Parse an optional ISO date that came from SQLite."""
    return date.fromisoformat(value) if value else None


def _result_source_date(result: SemanticSearchResult) -> date | None:
    """Return publication date, or effective date only when publication is absent."""
    value = result.publication_date or result.effective_date
    return date.fromisoformat(value) if value else None


def _assessment_run(
    assessment: OpportunityAssessment,
    retrieval: RetrievalResponse,
    response_id: str | None,
) -> AssessmentRun:
    """Convert dataclass retrieval rows into serializable evidence records."""
    evidence = []
    for item in retrieval.results:
        values = asdict(item)
        values.pop("vector_distance")
        evidence.append(RetrievedEvidence.model_validate(values))
    return AssessmentRun(assessment, retrieval.trace_id, evidence, response_id)
