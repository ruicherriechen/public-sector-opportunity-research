"""Create schema-validated, evidence-grounded opportunity assessments.

This module is the first generative layer built on the local RAG foundation.
``SemanticRetriever`` still decides which full-text chunks are relevant, while
``SQLiteStore`` separately provides exact award rows and dates. The OpenAI
Responses API receives only that bounded evidence and returns a Pydantic model
through Structured Outputs. This module then validates every citation and
applies deterministic status/date rules before returning the final model.

The workflow before this file is ingestion -> SQLite -> local embedding search
-> local cross-encoder reranking. After this file, ``demonstration.py`` saves a
before/after comparison for human and machine review. This is one reusable
assessment service, not a multi-agent system or an autonomous researcher.
"""

from __future__ import annotations

import json
import os
from dataclasses import asdict, dataclass
from datetime import date
from typing import Literal, Protocol, Sequence

from pydantic import BaseModel, ConfigDict, Field, model_validator

from .models import RetrievalResponse, SemanticSearchResult
from .retrieval import SemanticRetriever
from .storage import SQLiteStore


OpportunityStatus = Literal[
    "potential", "already_awarded", "partially_addressed", "insufficient_evidence"
]
StatementType = Literal["documented_fact", "model_inference"]
AwardScopeOverlap = Literal["none", "partial", "substantial", "unknown"]
ProcurementRecordStatus = Literal["intent_to_award", "confirmed_award"]
DocumentedProcurementStatus = Literal[
    "none", "intent_to_award", "confirmed_award", "conflicting_evidence"
]


class GroundedStatement(BaseModel):
    """Represent one fact or inference together with its evidence citations.

    ``statement_type`` makes the fact/inference distinction visible to readers.
    Source and chunk identifiers are generated by the local database, not by
    the language model. They are validated after the API response.
    """

    model_config = ConfigDict(extra="forbid")

    text: str = Field(description="Concise factual statement or explicit inference.")
    statement_type: StatementType
    source_document_ids: list[str]
    chunk_ids: list[str]


class RelevantDate(BaseModel):
    """Describe one source date with a deterministic database provenance link."""

    model_config = ConfigDict(extra="forbid")

    label: str
    date: date
    date_type: Literal["publication", "effective", "last_updated", "contract"]
    source_document_id: str


class DocumentedAward(BaseModel):
    """Hold deterministic procurement identity, status, and dates from SQLite."""

    model_config = ConfigDict(extra="forbid")

    document_id: str
    title: str
    procurement_status: ProcurementRecordStatus
    contract_id: str | None
    selected_vendor: str | None
    source_url: str | None
    publication_date: date | None
    effective_date: date | None
    execution_date: date | None
    last_updated_date: date | None


class OpportunityAssessmentDraft(BaseModel):
    """Define the strict Structured Outputs schema returned by the API.

    The model proposes a scope-overlap judgment and status, but deterministic
    Python rules calculate the final status after citation and chronology
    checks. Dates in the final output are also rebuilt from SQLite metadata.
    """

    model_config = ConfigDict(extra="forbid")

    agency: str
    opportunity_title: str
    agency_need_and_supporting_evidence: list[GroundedStatement]
    opportunity_status: OpportunityStatus
    documented_procurement_status: DocumentedProcurementStatus
    award_scope_overlap: AwardScopeOverlap
    commercial_implications: list[GroundedStatement]
    explanation_of_assessment: list[GroundedStatement]
    supporting_source_ids: list[str]
    supporting_chunk_ids: list[str]
    relevant_publication_and_contract_dates: list[RelevantDate]
    uncertainties_and_information_gaps: list[str]


class OpportunityAssessment(OpportunityAssessmentDraft):
    """Represent the final validated assessment returned to application code."""

    documented_awards: list[DocumentedAward]

    @model_validator(mode="after")
    def validate_status_consistency(self) -> "OpportunityAssessment":
        """Reject impossible combinations of procurement, overlap, and status.

        Chronology still belongs to deterministic application logic, but these
        invariants prevent a later code change from serializing the kind of
        contradiction seen in the earlier live report.
        """
        if self.opportunity_status == "already_awarded" and not (
            self.documented_procurement_status == "confirmed_award"
            and self.award_scope_overlap == "substantial"
        ):
            raise ValueError(
                "already_awarded requires a confirmed award and substantial overlap"
            )
        if self.opportunity_status == "partially_addressed" and not (
            self.documented_procurement_status == "confirmed_award"
            and self.award_scope_overlap == "partial"
        ):
            raise ValueError(
                "partially_addressed requires a confirmed award and partial overlap"
            )
        if self.documented_procurement_status in {"none", "intent_to_award"} and (
            self.opportunity_status in {"already_awarded", "partially_addressed"}
        ):
            raise ValueError(
                "intent or missing procurement evidence cannot be treated as executed"
            )
        if (
            self.documented_procurement_status == "conflicting_evidence"
            and self.opportunity_status != "insufficient_evidence"
        ):
            raise ValueError(
                "conflicting procurement evidence requires insufficient_evidence"
            )
        return self


