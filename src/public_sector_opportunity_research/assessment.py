    """Provide a JSON-friendly copy of one reranked retrieval result."""

    model_config = ConfigDict(extra="forbid")

    chunk_id: str
    document_id: str
    text: str
    agency_id: str
    agency_name: str
    document_title: str
    document_type: str
    source_url: str | None
